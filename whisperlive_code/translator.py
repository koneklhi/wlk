class LlamaTranslator(TranslatorBase):

    async def translate(self, content, language):
        from_lang = TranslatorBase.convert_lang_formal(language)
        to_lang = TranslatorBase.convert_lang_formal(TranslatorBase.get_to_lang(language))

        system_blocks = [self.get_static_system_text(from_lang, to_lang)]

        # 풀 프롬프트에서만 추가되는 부분
        glossary_rules_text = f"""
            5. GLOSSARY PRIORITY: Strictly follow the provided GLOSSARY for technical military terms to ensure consistency.
            6. Contextual Translation: While following the glossary, ensure the overall sentence structure is grammatically correct in {to_lang}.
            """
        prompt_manager = get_prompt_manager()
        glossary_part = prompt_manager.get_relevant_glossary(content)
        sentence_part = prompt_manager.get_sentence_block()

        if glossary_part:
            system_blocks.append(glossary_rules_text.strip())
            system_blocks.append(glossary_part)
        if sentence_part:
            system_blocks.append(sentence_part)

        vector_search_results = await asyncio.to_thread(
            self.vector_store.similarity_search, content, k=3
        )
        if vector_search_results:
            system_blocks.append("### EXAMPLES")
            for doc in vector_search_results:
                system_blocks.append(f"{doc.metadata.get('source', '')} : {doc.metadata.get('target', '')}")

        prompt = self.build_prompt(content, system_blocks)
        async for chunk in self._stream(prompt):
            yield chunk

