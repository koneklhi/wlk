    async def _stream(self, prompt):
        """실제 HTTP 스트리밍 공통 처리"""
        try:
            async with self.client.stream(
                "POST",
                "http://localhost:2010/v1/completions",
                headers={"Content-Type": "application/json"},
                json={
                    "model": self.model_name,
                    "prompt": prompt,
                    "use_beam_search": False,
                    "n": 1,
                    "temperature": 0.0,
                    "max_tokens": 1024,
                    "top_p": 1,
                    "top_k": 0,
                    "repeat_penalty": 1,
                    "stream": False
                }
            ) as response:
                response.raise_for_status()
                async for line in response.aiter_lines():
                    if not line:
                        continue
                    line = line.strip()
                    if line.startswith("data:"):
                        line = line[len("data:"):].strip()
                    if line == "[DONE]":
                        break
                    try:
                        data = json.loads(line)
                    except json.JSONDecodeError:
                        continue

                    choices = data.get("choices") or []
                    chunk = choices[0]
                    text_piece = chunk.get("text", "")

                    if text_piece:
                        if "<" in text_piece:
                            yield f"data: {json.dumps({'status': 'done'}, ensure_ascii=False)}\n\n"
                            return

                        if ":" in text_piece:
                            last = text_piece.rfind('"')
                            if last != -1:
                                prev = text_piece.rfind('"', 0, last)
                                if prev != -1:
                                    text_piece = text_piece[prev + 1: last]

                        yield f"data: {json.dumps({'content': text_piece}, ensure_ascii=False)}\n\n"

        except Exception:
            pass

        yield f"data: {json.dumps({'status': 'done'}, ensure_ascii=False)}\n\n"

